"""make_page_h.py - turns firmware/esp32s3_testbench/web/index.html into web_page.h (a C string in flash).
Run after editing the page:   python make_page_h.py
tools/testbench_sim.py serves the same index.html, so the browser test of the simulation and the robot match."""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
TB = os.path.join(HERE, "..", "esp32s3_testbench")
html = open(os.path.join(TB, "web", "index.html"), encoding="utf-8").read()
assert ")=====\"" not in html
out = ("// web_page.h - GENERATED by firmware/tools/make_page_h.py from web/index.html. Do not edit.\n#pragma once\n"
       "static const char INDEX_HTML[] PROGMEM = R\"=====(" + html + ")=====\";\n")
open(os.path.join(TB, "web_page.h"), "w", encoding="utf-8").write(out)
print("web_page.h: %d bytes of HTML" % len(html.encode("utf-8")))
